import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import { adminHref, canCreateWorld, gameHref, isAdminAccount, readStaffRole } from '../src/admin/gate.js';

const src = (rel) => readFileSync(new URL(rel, import.meta.url), 'utf8');

test('the guild master is sent to the ledger before a hunt can start', () => {
  const main = src('../src/main.js');
  const hunter = src('../supabase/functions/hunter/index.ts');
  const admin = src('../supabase/functions/admin/index.ts');
  const migration = src('../supabase/migrations/20261115230932_admin_ledger.sql');
  const page = src('../admin.html');
  assert.match(main, /if \(isAdminAccount\(readAccount\(\)\)\)/);
  assert.match(main, /location\.replace\(adminHref\(\)\)/);
  const boot = main.indexOf('function startGame');
  const construct = main.indexOf('new Game(', boot);
  assert.ok(boot > 0 && construct > boot);
  assert.match(main.slice(boot, construct), /isAdminAccount\(readAccount\(\)\)/);
  const apply = main.indexOf('async applyWallet');
  const sync = main.indexOf('syncHunt', apply);
  assert.ok(apply > 0 && sync > apply);
  assert.match(main.slice(apply, sync), /isAdminAccount\(session\)/);
  const submit = main.indexOf('async onAccountSubmit');
  const applyCall = main.indexOf('await this.applyWallet', submit);
  assert.ok(submit > 0 && applyCall > submit);
  assert.match(main.slice(submit, applyCall), /isAdminAccount\(session\)/);
  assert.match(main, /sendingToLedger/);
  const bootSkip = main.indexOf('if (!sendingToLedger && !glDeadAtBoot)');
  assert.ok(bootSkip > 0);
  assert.match(main.slice(0, bootSkip), /if \(sendingToLedger\) location\.replace\(adminHref\(\)\)/);
  assert.match(hunter, /keepsLedger/);
  assert.match(hunter, /from\("admins"\)/);
  assert.match(hunter, /select\("email, role"\)/);
  assert.match(hunter, /role === "master"/);
  assert.match(hunter, /It does not enter the hunt/);
  assert.match(admin, /admin_account_facts/);
  assert.match(admin, /admin_wallet_facts/);
  assert.match(admin, /This gate is for the guild master/);
  assert.match(admin, /body.op === "promote"/);
  assert.match(admin, /body.op === "demote"/);
  assert.match(admin, /role: "moderator"/);
  assert.match(admin, /Only the guild master can change staff/);
  assert.match(src('../src/admin/api.js'), /buildLedger/);
  assert.match(src('../src/admin/api.js'), /changeStaff/);
  assert.match(migration, /monstergateonline@gmail\.com/);
  assert.match(migration, /admin_hunt_facts/);
  assert.match(page, /Guild ledger/);
  assert.match(page, /src\/admin\/main\.js/);
  assert.doesNotMatch(page, /src\/main\.js/);
  assert.match(src('../vite.config.js'), /admin\.html/);
  const css = src('../src/admin/admin.css');
  const adminMain = src('../src/admin/main.js');
  const migrationRole = src('../supabase/migrations/20261116010000_admin_moderator_role.sql');
  assert.match(adminMain, /documentElement\.classList\.add\('ledger'\)/);
  assert.match(adminMain, /dataset.promote/);
  assert.match(adminMain, /changeStaff/);
  assert.match(adminMain, /isAdminAccount/);
  assert.match(adminMain, /location\.replace\(gameHref\(\)\)/);
  assert.match(src('../src/ui/hud.js'), /canCreateWorld\(game\.staffRole\)/);
  assert.match(src('../src/ui/hud.js'), /World Creator/);
  assert.match(src('../src/ui/hud.js'), /if \(canCreateWorld\(game\.staffRole\)\)/);
  assert.match(hunter, /staffKind/);
  assert.match(hunter, /role === "moderator"/);
  assert.match(hunter, /staff,/);
  assert.match(css, /html\.ledger/);
  assert.match(css, /overflow-y:\s*auto/);
  assert.match(css, /touch-action:\s*pan-y/);
  assert.match(css, /touch-action:\s*manipulation/);
  assert.match(css, /\.hunters td::before/);
  assert.match(css, /overflow-wrap:\s*anywhere/);
  assert.match(css, /@media \(max-width: 980px\) \{[\s\S]*\.tools \{[\s\S]*display:\s*grid/);
  assert.match(css, /@media \(max-width: 980px\) \{[\s\S]*\.rail \{[\s\S]*repeat\(2,\s*minmax\(0,\s*1fr\)\)/);
  assert.match(css, /\.hunters thead \{ display: none/);
  assert.match(css, /\.hunters td > \* \{[\s\S]*grid-column:\s*2/);
  assert.match(css, /\.tools input,[\s\S]*\.seg-row,[\s\S]*\.chips,[\s\S]*\.note \{[\s\S]*width:\s*100%/);
  assert.doesNotMatch(css, /\.table-wrap \{[^}]*overflow:\s*visible/);
  assert.match(migrationRole, /role in \('master', 'moderator'\)/);
  assert.match(src('../src/admin/view.js'), /Make moderator/);
  assert.ok(adminMain.indexOf("import '../ui/theme.css'") < adminMain.indexOf("import './admin.css'"));
  assert.equal(adminHref(), '/admin.html');
  assert.equal(gameHref(), '/');
  assert.equal(isAdminAccount({ kind: 'email', email: 'monstergateonline@gmail.com' }), true);
  assert.equal(isAdminAccount({ kind: 'email', email: 'bram@hunt.test' }), false);
  assert.equal(isAdminAccount({ kind: 'guest', email: 'monstergateonline@gmail.com' }), false);
  assert.equal(isAdminAccount(null), false);
  assert.equal(readStaffRole('moderator'), 'moderator');
  assert.equal(readStaffRole('master'), '');
  assert.equal(canCreateWorld('moderator'), true);
  assert.equal(canCreateWorld(''), false);
  assert.equal(canCreateWorld('master'), false);
});
